namespace RimeTts.Domains.Seg;

using RimeTts.Cfg;

[Doc($$"""
句子劃分的設定。

*為何要劃分*：使用者是逐字詞上屏的，一次上屏往往只是一個詞。
逐詞翻譯再逐詞朗讀會碎成一地；所以要等一小段時間沒有新上屏（或上屏以句末標點結尾），
才把累積的文字當成一句送進翻譯。

*兩個條件的關係*：終止符是「立刻成句」，間隔是「拖太久就當你說完了」。
終止符清單為空時只剩間隔，這是刻意的：有些輸入法上屏的是詞，不會帶標點。
""")]
public class OptSentenceSeg{

	[Doc($$"""
	無上屏間隔（毫秒）。自最後一次收到上屏起算，超過這個時間就成句。

	*這是唯一的「等」*：本工具沒有回車確認的機制，全靠這個時間窗。
	*默認值（5000）的唯一出處是 `KeysAppCfg.SentenceSeg.NoCommitGapMs`*；
	本屬性不帶默認（0 僅是「未映射」佔位，生產路徑一律由 `CfgMapper` 賦值，
	且 `DiCore` 會驗證必須為正）——兩處各寫一份必然漂移（2026-11-16 審查 ARCH-2）。
	""")]
	public i64 NoCommitGapMs{get;set;} = 0;

	[Doc($$"""
	成句終止符列表。上屏文本的最後一個字符是其中之一時，立刻成句（不必等間隔）。
	為空＝只按間隔成句。

	*只比最後一個字符*：一次上屏可能帶整句（貼上、候選整句上屏），
	比「包含」會讓句中的逗號也觸發成句。
	""")]
	public IList<str> SentenceTerminators{get;set;} = new List<str>();
}
